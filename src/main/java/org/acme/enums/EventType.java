package org.acme.enums;

/**
 * Тип события в хронологии документа.
 *
 * <p>Значения сохраняются в БД строкой ({@code @Enumerated(EnumType.STRING)}),
 * поэтому переименование констант требует миграции данных.</p>
 */
public enum EventType {

    /** Документ создан (первая версия). */
    CREATED,

    /** Загружена новая версия файла. */
    UPLOADED,

    /** Изменены метаданные документа (title, docKind). */
    METADATA_CHANGED,

    /** Изменён статус документа. */
    STATUS_CHANGED,

    /** Документ помечен удалённым (soft delete). */
    DELETED,

    /** Документ восстановлен из удалённых. */
    RESTORED,

    /** Добавлен комментарий к версии. */
    COMMENTED,

    /** Выполнен откат к одной из предыдущих версий. */
    ROLLED_BACK
}